/* ==========================================================================
   THE STANDARD THE PAGE IS HELD TO.

   One paragraph, in one place, sent to every call that designs anything —
   stage 1 when it is choosing bands, and stage 2b whether it is filling bands
   or designing the whole page in free mode. Written once because a standard
   that says something different in two prompts is two standards.

   WHY IT IS NOT JUST ADJECTIVES. "Professional, beautiful, wow" is what every
   model already believes it is doing, so a line made of those words changes
   nothing: there is no answer it rules out. What follows keeps the ask — it
   is the ask — and gives it the one thing an adjective cannot carry, which is
   a test the model can fail. "What would a visitor remember about this section
   an hour later" has a wrong answer, and a section with no answer to it is the
   exact failure this exists to stand against: correct, present, and not worth
   a second look.

   The audience is named for the same reason. "For merchants" is nobody;
   someone who looks at storefronts for a living and will hold this next to the
   best one they saw this month is a real reader with a real bar.

   THE SECOND HALF names two sections and asks for more invention in them: the
   opening and the buy box. It is not the checklist that used to sit further
   down this prompt — that was cut deliberately, because a list of what a good
   buy box contains is how every store in a trade ends up with the same one.
   This asks for the opposite of a list, and carries its own test: a hero that
   survives having its words swapped for a competitor's was never this store's
   hero. That test has a wrong answer. "Beautiful" does not.
   ========================================================================== */

